#!/usr/bin/env python3
"""Run the archived six-protein calibration with its original Python 3.14 code.

The manuscript's 18.8832% MRE result was generated by the archived bytecode in
``legacy_runtime``.  A later source edit changed the numerical model and no
longer reproduces that result.  This launcher loads the exact historical
module before executing the preserved scan driver, keeping the package
self-contained and preventing an accidental switch to the later model.
"""
from __future__ import annotations

import importlib.machinery
import importlib.util
import runpy
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
LEGACY_PYC = ROOT / "legacy_runtime" / "simulate_sixgene_pool_chain_v3.cpython-314.pyc"

if sys.version_info[:2] != (3, 14):
    raise RuntimeError(
        "The archived six-protein runtime requires CPython 3.14; "
        f"current interpreter is {sys.version.split()[0]}."
    )
if not LEGACY_PYC.exists():
    raise FileNotFoundError(LEGACY_PYC)

sys.path.insert(0, str(SRC))
loader = importlib.machinery.SourcelessFileLoader(
    "simulate_sixgene_pool_chain_v3", str(LEGACY_PYC)
)
spec = importlib.util.spec_from_loader(loader.name, loader)
if spec is None:
    raise RuntimeError(f"Cannot create import specification for {LEGACY_PYC}")
module = importlib.util.module_from_spec(spec)
sys.modules[loader.name] = module
loader.exec_module(module)

runpy.run_path(str(SRC / "run_unified_shared_scan.py"), run_name="__main__")
